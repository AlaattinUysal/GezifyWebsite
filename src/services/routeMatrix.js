export function getMatrixData(id1, id2) {
    if (id1 === id2) return { mode: 'walking', distance: 0, duration: 0 };
    
    // İskeleye (port) yapılan kara/yürüme rotaları için ana konumu baz al.
    // Salacak İskelesi (port_6) -> Kız Kulesi'nin (6) karadaki konumu olarak kabul edildi.
    // Kabataş İskelesi (port_9) -> Taksim'e (13) veya Dolmabahçe'ye yakın, biz Taksim'in sürelerini baz alabiliriz.
    const normalizeId = (id) => {
        const strId = String(id);
        if (strId === 'port_6') return 6;
        if (strId === 'port_9') return 13;
        return Number(id);
    };

    const nId1 = normalizeId(id1);
    const nId2 = normalizeId(id2);

    if (nId1 === nId2) return { mode: 'walking', distance: 0, duration: 0 };

    const key = `${Math.min(nId1, nId2)}-${Math.max(nId1, nId2)}`;
    return routeMatrix[key];
}
